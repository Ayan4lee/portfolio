-- Portfolio schema: run once in the Supabase SQL editor.
create table if not exists public.site_profile (
  id integer primary key default 1 check (id = 1),
  full_name varchar(120) not null,
  headline varchar(180) not null,
  tagline varchar(240),
  short_bio varchar(600),
  long_bio text,
  profile_image_url text,
  location varchar(160),
  public_email varchar(254),
  resume_url text,
  github_url text,
  linkedin_url text,
  career_start_date date,
  updated_at timestamptz not null default now()
);
create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name varchar(80) not null unique,
  slug varchar(100) not null unique
);
create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  title varchar(120) not null,
  slug varchar(150) not null unique,
  summary varchar(220) not null,
  description text not null,
  category_id bigint references public.categories(id) on delete set null,
  tech_stack text[] not null default '{}',
  image_url text,
  live_url text,
  repo_url text,
  project_date date,
  is_featured boolean not null default false,
  is_published boolean not null default false,
  display_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.skills (
  id bigint generated by default as identity primary key,
  name varchar(100) not null,
  category varchar(80) not null,
  proficiency smallint not null default 0 check (proficiency between 0 and 100),
  started_on date,
  icon_name varchar(80),
  display_order integer not null default 0
);
create table if not exists public.education (
  id bigint generated by default as identity primary key,
  institution varchar(180) not null,
  degree varchar(140) not null,
  field_of_study varchar(140),
  start_date date not null,
  end_date date,
  grade varchar(80),
  description text,
  display_order integer not null default 0,
  constraint education_dates_valid check (end_date is null or end_date >= start_date)
);
create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name varchar(100) not null,
  email varchar(254) not null,
  subject varchar(150) not null,
  message varchar(2000) not null,
  created_at timestamptz not null default now(),
  is_read boolean not null default false,
  ip_hash varchar(128)
);
create table if not exists public.admin_users (
  id bigint generated by default as identity primary key,
  username varchar(80) not null unique,
  password_hash text not null,
  created_at timestamptz not null default now(),
  last_login_at timestamptz,
  failed_attempts integer not null default 0,
  locked_until timestamptz
);
create index if not exists projects_public_order_idx on public.projects(is_published, display_order);
create index if not exists projects_category_idx on public.projects(category_id);
create index if not exists contact_messages_created_idx on public.contact_messages(created_at desc);
